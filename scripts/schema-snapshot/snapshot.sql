-- The catalog query behind `pnpm schema:snapshot` (scripts/schema-snapshot/run.mjs).
-- Read-only. Returns ONE json array [{path, content}, ...]: every file of
-- supabase/schema-snapshot/, sorted by path. No OIDs, no timestamps, no versions.
-- Runs against the local stack (CI, dev) and, read-only, against production (release drift check).
with
  roles(role_name) as (values ('anon'), ('authenticated'), ('service_role')),
  -- The app's own schemas. `private` is the half members never reach directly (the sweep
  -- functions, the queues, the search index); `storage` and `auth` are the platform's, but the
  -- policies on their tables and the triggers on them are ours.
  app_schemas(schema_name) as (values ('public'), ('private')),
  -- Objects whose privileges and policies are worth recording (platform tables included).
  own_schemas(schema_name) as (values ('public'), ('private'), ('storage')),
  -- Where a trigger of ours may sit: our tables, and the platform's that carry one of ours
  -- (auth.users on a new member, storage.objects on an avatar).
  trigger_schemas(schema_name) as (values ('public'), ('private'), ('storage'), ('auth')),
  app_ns as (select n.oid, n.nspname from pg_namespace n join app_schemas s on s.schema_name = n.nspname),
  own_ns as (select n.oid, n.nspname from pg_namespace n join own_schemas s on s.schema_name = n.nspname),
  trigger_ns as (select n.oid, n.nspname from pg_namespace n join trigger_schemas s on s.schema_name = n.nspname),
  ext_objs as (select objid from pg_depend where deptype = 'e'),
  rels as (
    select c.oid, c.relname, c.relkind, c.relowner, c.relacl, c.reloptions, c.relrowsecurity, c.relforcerowsecurity,
           n.nspname, format('%I.%I', n.nspname, c.relname) as qname
      from pg_class c
      join own_ns n on n.oid = c.relnamespace
     where c.relkind in ('r', 'p', 'v', 'm')
       and c.oid not in (select objid from ext_objs)
  ),
  app_rels as (select * from rels where nspname in (select schema_name from app_schemas)),
  -- grantee 0 is PUBLIC
  fmt_grantee as (select 0::oid as oid, 'public'::text as name
                  union all select r.oid, r.rolname from pg_roles r where r.rolname in (select role_name from roles)),

  -- ---------------------------------------------------------------- functions
  funcs as (
    select p.oid, p.proacl, p.proowner,
           format('%I.%I(%s)', n.nspname, p.proname,
                  regexp_replace(oidvectortypes(p.proargtypes), '\s+', '', 'g')) as sig
      from pg_proc p
      join app_ns n on n.oid = p.pronamespace
     where p.prokind in ('f', 'p')
       and p.oid not in (select objid from ext_objs)
  ),
  func_files as (
    select 'functions/' || case when length(sig) > 150 then left(sig, 140) || '-' || left(md5(sig), 8) else sig end || '.sql' as path,
           pg_get_functiondef(oid) || E';\n' as content
      from funcs
  ),

  -- ------------------------------------------------------------------- tables
  col_lines as (
    select a.attrelid as oid,
           string_agg(
             format('  %I %s%s%s%s', a.attname, format_type(a.atttypid, a.atttypmod),
                    case a.attidentity when 'a' then ' generated always as identity' when 'd' then ' generated by default as identity' else '' end,
                    case when a.attgenerated = 's' then format(' generated always as (%s) stored', pg_get_expr(d.adbin, d.adrelid))
                         when d.adbin is not null and a.attidentity = '' then ' default ' || pg_get_expr(d.adbin, d.adrelid) else '' end,
                    case when a.attnotnull then ' not null' else '' end),
             E',\n' order by a.attnum) as body
      from pg_attribute a
      left join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
     where a.attnum > 0 and not a.attisdropped
     group by a.attrelid
  ),
  con_lines as (
    select r.oid,
           string_agg(format('alter table %s add constraint %I %s;', r.qname, k.conname, pg_get_constraintdef(k.oid)), E'\n' order by k.conname) as body
      from app_rels r join pg_constraint k on k.conrelid = r.oid
     where k.contype in ('p', 'u', 'f', 'c', 'x')
     group by r.oid
  ),
  idx_lines as (
    select r.oid,
           string_agg(pg_get_indexdef(i.indexrelid) || ';', E'\n' order by ic.relname) as body
      from app_rels r
      join pg_index i on i.indrelid = r.oid
      join pg_class ic on ic.oid = i.indexrelid
     where not exists (select 1 from pg_constraint k where k.conindid = i.indexrelid and k.contype in ('p', 'u', 'x'))
     group by r.oid
  ),
  -- table / view / sequence privileges, table-level
  rel_priv as (
    select r.oid, r.qname, r.relkind, g.name as grantee, p.privilege_type,
           format('grant %s on %s %s to %s;', lower(p.privilege_type),
                  case when r.relkind in ('v', 'm') then 'table' else 'table' end, r.qname, g.name) as line
      from rels r
      cross join lateral aclexplode(coalesce(r.relacl, acldefault('r', r.relowner))) p
      join fmt_grantee g on g.oid = p.grantee
  ),
  -- column-level privileges
  col_priv as (
    select r.oid, r.qname, g.name as grantee,
           format('grant %s (%I) on table %s to %s;', lower(p.privilege_type), a.attname, r.qname, g.name) as line
      from rels r
      join pg_attribute a on a.attrelid = r.oid and a.attnum > 0 and not a.attisdropped and a.attacl is not null
      cross join lateral aclexplode(a.attacl) p
      join fmt_grantee g on g.oid = p.grantee
  ),
  all_priv_lines as (
    select oid, qname, line from rel_priv
    union all select oid, qname, line from col_priv
  ),
  priv_agg as (
    select oid, string_agg(line, E'\n' order by line) as body from all_priv_lines group by oid
  ),
  table_files as (
    select 'tables/' || r.qname || '.sql' as path,
           format(E'create table %s (\n%s\n);\n', r.qname, c.body)
           || coalesce(E'\n-- constraints\n' || k.body || E'\n', '')
           || coalesce(E'\n-- indexes\n' || i.body || E'\n', '')
           || E'\n-- row level security\n'
           || case when r.relrowsecurity then format('alter table %s enable row level security;', r.qname)
                   else format('-- row level security is OFF on %s', r.qname) end
           || case when r.relforcerowsecurity then format(E'\nalter table %s force row level security;', r.qname) else '' end
           || coalesce(E'\n\n-- grants (anon, authenticated, service_role, public)\n' || pa.body, E'\n\n-- no grants to anon, authenticated, service_role, public')
           || E'\n' as content
      from app_rels r
      join col_lines c on c.oid = r.oid
      left join con_lines k on k.oid = r.oid
      left join idx_lines i on i.oid = r.oid
      left join priv_agg pa on pa.oid = r.oid
     where r.relkind in ('r', 'p')
  ),

  -- -------------------------------------------------------------------- views
  view_files as (
    select 'views/' || r.qname || '.sql' as path,
           format(E'create %s %s%s as\n%s\n',
                  case r.relkind when 'm' then 'materialized view' else 'view' end, r.qname,
                  case when r.reloptions is not null
                       then ' with (' || (select string_agg(o, ', ' order by o) from unnest(r.reloptions) o) || ')' else '' end,
                  rtrim(pg_get_viewdef(r.oid, true), ';') || ';')
           || coalesce(E'\n-- indexes\n' || i.body || E'\n', '')
           || coalesce(E'\n-- grants (anon, authenticated, service_role, public)\n' || pa.body || E'\n', '') as content
      from app_rels r
      left join idx_lines i on i.oid = r.oid
      left join priv_agg pa on pa.oid = r.oid
     where r.relkind in ('v', 'm')
  ),

  -- ---------------------------------------------------------------- triggers
  trig as (
    select format('%I.%I', n.nspname, c.relname) as qname, t.tgname, t.tgenabled,
           pg_get_triggerdef(t.oid, true) as def
      from pg_trigger t
      join pg_class c on c.oid = t.tgrelid
      join trigger_ns n on n.oid = c.relnamespace
      join pg_proc p on p.oid = t.tgfoid
     where not t.tgisinternal
       and p.pronamespace in (select oid from app_ns)
  ),
  trigger_files as (
    select 'triggers/' || qname || '.sql' as path,
           string_agg(def || ';' || case when tgenabled = 'D' then format(E'\nalter table %s disable trigger %I;', qname, tgname) else '' end,
                      E'\n\n' order by tgname) || E'\n' as content
      from trig group by qname
  ),

  -- ---------------------------------------------------------------- policies
  pol as (
    select r.qname, pc.polname,
           format('create policy %I on %s as %s for %s to %s%s%s;',
                  pc.polname, r.qname,
                  case when pc.polpermissive then 'permissive' else 'restrictive' end,
                  case pc.polcmd when 'r' then 'select' when 'a' then 'insert' when 'w' then 'update' when 'd' then 'delete' else 'all' end,
                  case when pc.polroles = '{0}' then 'public'
                       else (select string_agg(ro.rolname, ', ' order by ro.rolname) from pg_roles ro where ro.oid = any (pc.polroles)) end,
                  case when pc.polqual is not null then E'\n  using (' || pg_get_expr(pc.polqual, pc.polrelid) || ')' else '' end,
                  case when pc.polwithcheck is not null then E'\n  with check (' || pg_get_expr(pc.polwithcheck, pc.polrelid) || ')' else '' end) as def
      from pg_policy pc join rels r on r.oid = pc.polrelid
  ),
  policy_files as (
    select 'policies/' || qname || '.sql' as path,
           string_agg(def, E'\n\n' order by polname) || E'\n' as content
      from pol group by qname
  ),

  -- ------------------------------------------------------------------- grants
  schema_grants as (
    select format('grant %s on schema %I to %s;', lower(p.privilege_type), n.nspname, g.name) as line
      from pg_namespace n
      cross join lateral aclexplode(coalesce(n.nspacl, acldefault('n', n.nspowner))) p
      join fmt_grantee g on g.oid = p.grantee
     where n.nspname in (select schema_name from own_schemas)
  ),
  func_grants as (
    select format('grant execute on function %s to %s;', f.sig, g.name) as line
      from funcs f
      cross join lateral aclexplode(coalesce(f.proacl, acldefault('f', f.proowner))) p
      join fmt_grantee g on g.oid = p.grantee
  ),
  seq_grants as (
    select format('grant %s on sequence %s to %s;', lower(p.privilege_type), format('%I.%I', n.nspname, c.relname), g.name) as line
      from pg_class c
      join app_ns n on n.oid = c.relnamespace
      cross join lateral aclexplode(coalesce(c.relacl, acldefault('S', c.relowner))) p
      join fmt_grantee g on g.oid = p.grantee
     where c.relkind = 'S'
  ),
  default_grants as (
    select format('alter default privileges for role %s in schema %s grant %s on %s to %s;',
                  pg_get_userbyid(d.defaclrole), coalesce(n.nspname, '(all schemas)'), lower(p.privilege_type),
                  case d.defaclobjtype when 'r' then 'tables' when 'S' then 'sequences' when 'f' then 'functions' when 'n' then 'schemas' when 'T' then 'types' end,
                  g.name) as line
      from pg_default_acl d
      left join pg_namespace n on n.oid = d.defaclnamespace
      cross join lateral aclexplode(d.defaclacl) p
      join fmt_grantee g on g.oid = p.grantee
     where coalesce(n.nspname, 'public') in (select schema_name from app_schemas)
  ),
  grant_files as (
    select 'grants/schemas.sql' as path, coalesce(string_agg(line, E'\n' order by line), '-- none') || E'\n' as content from schema_grants
    union all select 'grants/tables.sql', coalesce(string_agg(line, E'\n' order by line), '-- none') || E'\n'
      from (select distinct line from all_priv_lines) x
    union all select 'grants/functions.sql', coalesce(string_agg(line, E'\n' order by line), '-- none') || E'\n' from func_grants
    union all select 'grants/sequences.sql', coalesce(string_agg(line, E'\n' order by line), '-- none') || E'\n' from seq_grants
    union all select 'grants/default-privileges.sql', coalesce(string_agg(line, E'\n' order by line), '-- none') || E'\n' from default_grants
  ),

  -- ---------------------------------------------------------- types, extensions
  type_files as (
    select 'types/' || format('%I.%I', n.nspname, t.typname) || '.sql' as path,
           format(E'create type %I.%I as enum (\n%s\n);\n', n.nspname, t.typname,
                  (select string_agg(format('  %L', e.enumlabel), E',\n' order by e.enumsortorder) from pg_enum e where e.enumtypid = t.oid)) as content
      from pg_type t join app_ns n on n.oid = t.typnamespace
     where t.typtype = 'e' and t.oid not in (select objid from ext_objs)
  ),
  extension_files as (
    select 'extensions.sql' as path,
           coalesce(string_agg(format('create extension if not exists %I with schema %I;', e.extname, n.nspname), E'\n' order by e.extname), '-- none') || E'\n' as content
      from pg_extension e join pg_namespace n on n.oid = e.extnamespace
     where e.extname <> 'plpgsql'
  ),

  -- ---------------------------------------------------------------- cron, realtime
  cron_files as (
    select 'cron/jobs.sql' as path,
           coalesce(string_agg(
             format(E'-- %s%s\nselect cron.schedule(%L, %L, $job$%s$job$);',
                    coalesce(j.jobname, '(unnamed)'), case when j.active then '' else ' (INACTIVE)' end,
                    j.jobname, j.schedule, j.command),
             E'\n\n' order by j.jobname, j.command), '-- no jobs') || E'\n' as content
      from cron.job j
  ),
  publication_files as (
    select 'realtime/publication.sql' as path,
           coalesce(string_agg(body, E'\n\n' order by pubname), '-- no publications') || E'\n' as content
      from (
        select p.pubname,
               format(E'-- publication %I (insert=%s update=%s delete=%s truncate=%s all tables=%s)\n%s',
                      p.pubname, p.pubinsert, p.pubupdate, p.pubdelete, p.pubtruncate, p.puballtables,
                      coalesce((select string_agg(format('alter publication %I add table %I.%I%s%s;', pt.pubname, pt.schemaname, pt.tablename,
                                                          case when pt.attnames is not null and cardinality(pt.attnames) > 0
                                                                    and cardinality(pt.attnames) < (select count(*) from pg_attribute a where a.attrelid = format('%I.%I', pt.schemaname, pt.tablename)::regclass and a.attnum > 0 and not a.attisdropped)
                                                               then ' (' || array_to_string(pt.attnames, ', ') || ')' else '' end,
                                                          case when pt.rowfilter is not null then ' where (' || pt.rowfilter || ')' else '' end),
                                                 E'\n' order by pt.schemaname, pt.tablename)
                                  from pg_publication_tables pt where pt.pubname = p.pubname), '-- no tables')) as body
          from pg_publication p
         where p.pubname not like 'pg\_%'
      ) pubs
  ),

  files as (
    select path, content from func_files
    union all select path, content from table_files
    union all select path, content from view_files
    union all select path, content from trigger_files
    union all select path, content from policy_files
    union all select path, content from grant_files
    union all select path, content from type_files
    union all select path, content from extension_files
    union all select path, content from cron_files
    union all select path, content from publication_files
  )
select jsonb_agg(jsonb_build_object('path', path, 'content', content) order by path)::text as snapshot from files;
