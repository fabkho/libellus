// The dry run: translate a small, varied sample of en.json into a scratch folder and check it.
//
//   node scripts/i18n/sample.mjs [--models a,b] [--primary a] [--force]
//
// Never touches i18n/locales: every model gets its own copy under web/.i18n-sample/ (git-ignored) holding
// only the sample's keys. No token accounting: the pass-through proxy that added up the API's `usageMetadata` for the cost estimate in docs/i18n/README.md is gone.
// Afterwards docs/i18n/german-sample.md is rendered from the results plus scripts/i18n/sample-notes.md.
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { DEFAULT_MODEL, translate } from './run.mjs'
import { flatten, verify } from './verify.mjs'

const here = dirname(fileURLToPath(import.meta.url))
const web = resolve(here, '..', '..')
const root = resolve(web, '..')
const scratch = join(web, '.i18n-sample')
const argv = process.argv.slice(2)
const opt = name => { const i = argv.indexOf(`--${name}`); return i === -1 ? undefined : argv[i + 1] }

const models = (opt('models') ?? DEFAULT_MODEL).split(',')
const primary = opt('primary') ?? models[0]
const force = argv.includes('--force')

const sample = JSON.parse(readFileSync(join(here, 'sample-keys.json'), 'utf8'))
const en = JSON.parse(readFileSync(join(web, 'i18n', 'locales', 'en.json'), 'utf8'))
const enFlat = flatten(en)
const sampleFlat = { ...Object.fromEntries(sample.keys.map(k => [k, enFlat[k]])), ...sample.synthetic }
for (const [k, v] of Object.entries(sampleFlat)) if (typeof v !== 'string') throw new Error(`sample key ${k} is not in en.json`)

function nest(flat) {
  const out = {}
  for (const [key, value] of Object.entries(flat)) {
    const parts = key.split('.')
    let node = out
    for (const part of parts.slice(0, -1)) node = node[part] ??= {}
    node[parts.at(-1)] = value
  }
  return out
}

async function runModel(model) {
  const dir = join(scratch, model)
  if (existsSync(join(dir, 'i18n', 'locales', 'de.json')) && !force) return { dir, cached: true }
  rmSync(dir, { recursive: true, force: true })
  mkdirSync(join(dir, 'i18n', 'locales'), { recursive: true })
  writeFileSync(join(dir, 'i18n', 'locales', 'en.json'), `${JSON.stringify(nest(sampleFlat), null, 2)}\n`)
  const started = Date.now()
  translate(dir, ['--model', model])
  writeFileSync(join(dir, 'seconds.txt'), String(((Date.now() - started) / 1000).toFixed(1)))
  return { dir, cached: false }
}

const results = {}
for (const model of models) {
  console.log(`\n== ${model}`)
  const { dir } = await runModel(model)
  const de = JSON.parse(readFileSync(join(dir, 'i18n', 'locales', 'de.json'), 'utf8'))
  const enSample = JSON.parse(readFileSync(join(dir, 'i18n', 'locales', 'en.json'), 'utf8'))
  results[model] = { dir, de: flatten(de), check: verify(enSample, de), seconds: existsSync(join(dir, 'seconds.txt')) ? readFileSync(join(dir, 'seconds.txt'), 'utf8') : '?' }
  console.log(`   ${JSON.stringify(results[model].check.stats)}`)
}

writeFileSync(join(scratch, 'summary.json'), JSON.stringify({ primary, models: Object.fromEntries(Object.entries(results).map(([m, r]) => [m, { stats: r.check.stats, seconds: r.seconds, errors: r.check.errors, warnings: r.check.warnings }])) }, null, 2))

// ---- render docs/i18n/german-sample.md --------------------------------------------------------
const esc = text => String(text ?? '').replace(/\\/g, '\\\\').replace(/\|/g, '\\|').replace(/\n/g, ' ')
const code = text => `\`${esc(text).replace(/`/g, "'")}\``
const main = results[primary]
const lines = []
lines.push('# German sample: the dry run', '')
lines.push('Generated by `node scripts/i18n/sample.mjs` from `scripts/i18n/sample-keys.json`; the review notes at the end are written by hand (`scripts/i18n/sample-notes.md`). Nothing here is in `de.json`: the app is not translated yet.', '')
lines.push(`Translated with **the-i18n-kit** (\`${'@the-i18n-kit/cli@8.3.0'}\`) through the Gemini API, model **\`${primary}\`**, informal *du*, with \`web/i18n/kit/ai-context.md\`, \`glossary.json\` and \`examples.json\`. ${sample.keys.length} real keys of \`en.json\` and ${Object.keys(sample.synthetic).length} synthetic ones (no \`@:\` link exists in \`en.json\` yet).`, '')
lines.push('## Automatic checks', '')
const stats = main.check.stats
lines.push(`| Check | Result |`, `| --- | --- |`)
lines.push(`| Same key set as the sample | ${main.check.errors.some(e => e.kind === 'missing' || e.kind === 'extra') ? 'NO' : `yes, ${stats.keys} of ${stats.keys}`} |`)
for (const [kind, label] of [['placeholder', 'Identical `{placeholders}` (per plural form)'], ['plural', 'Identical plural separators `\\|` (same number of forms)'], ['link', 'Identical `@:` links'], ['literal', "Identical `{'@'}` literals"]]) {
  const bad = main.check.errors.filter(e => e.kind === kind)
  lines.push(`| ${label} | ${bad.length ? `**${bad.length} wrong**: ${bad.map(b => b.key).join(', ')}` : 'yes'} |`)
}
const unchanged = main.check.warnings.filter(w => w.kind === 'unchanged' || w.kind === 'english')
lines.push(`| No leftover English | ${unchanged.length ? `check: ${unchanged.map(w => `${w.key} (${w.detail})`).join('; ')}` : 'yes'} |`)
lines.push(`| Length ratio German / English (characters, placeholders removed) | median ×${stats.medianRatio}, 90th percentile ×${stats.p90Ratio}, max ×${stats.maxRatio} |`)
const otherWarn = main.check.warnings.filter(w => !['unchanged', 'english'].includes(w.kind))
lines.push(`| Other warnings | ${otherWarn.length ? otherWarn.map(w => `${w.key}: ${w.kind} (${w.detail})`).join('; ') : 'none'} |`, '')
lines.push('## Side by side', '', 'One table per kind of string. `{…}` and `\\|` are the app\'s placeholders and plural separators.', '')
const shown = new Set()
for (const [kind, keys] of Object.entries(sample.kinds)) {
  lines.push(`### ${kind[0].toUpperCase()}${kind.slice(1)}`, '', '| Key | English | German | × |', '| --- | --- | --- | --- |')
  for (const key of keys) {
    const s = sampleFlat[key]
    const t = main.de[key]
    const ratio = t ? (t.replace(/\{[^}]*\}/g, '').length / Math.max(1, s.replace(/\{[^}]*\}/g, '').length)).toFixed(2) : '–'
    lines.push(`| ${code(key)} | ${code(s)} | ${code(t)} | ${ratio} |`)
    shown.add(key)
  }
  lines.push('')
}
const rest = Object.keys(sampleFlat).filter(k => !shown.has(k))
if (rest.length) {
  lines.push('### Other', '', '| Key | English | German | × |', '| --- | --- | --- | --- |')
  for (const key of rest) lines.push(`| ${code(key)} | ${code(sampleFlat[key])} | ${code(main.de[key])} | ${(main.de[key].replace(/\{[^}]*\}/g, '').length / Math.max(1, sampleFlat[key].replace(/\{[^}]*\}/g, '').length)).toFixed(2)} |`)
  lines.push('')
}
if (models.length > 1) {
  lines.push('## Model comparison', '', `The same ${sample.keys.length + Object.keys(sample.synthetic).length} strings, same context, same settings (the kit sends temperature 0 and the least thinking each model accepts).`, '')
  lines.push('| Model | Errors | Warnings | Median × | Seconds |', '| --- | --- | --- | --- | --- |')
  for (const model of models) {
    const r = results[model]
    lines.push(`| \`${model}\` | ${r.check.stats.errors} | ${r.check.stats.warnings} | ${r.check.stats.medianRatio} | ${r.seconds} |`)
  }
  lines.push('')
  const fifteen = ['status.want_to_read', 'status.reading', 'status.finished', 'status.notFinished', 'profile.account.delete', 'sync.syncing', 'profile.records.days', 'collection.moved', 'friends.want', 'auth.error.invite_gone', 'home.loadError', 'feed.emptyTitle', 'feed.empty', 'home.installHint.text', 'privacy.goPublicText']
  lines.push('| Key | English | ' + models.map(m => `\`${m}\``).join(' | ') + ' |', '| --- | --- | ' + models.map(() => '---').join(' | ') + ' |')
  for (const key of fifteen) lines.push(`| ${code(key)} | ${code(sampleFlat[key])} | ${models.map(m => code(results[m].de[key])).join(' | ')} |`)
  lines.push('')
}
const notesPath = join(here, 'sample-notes.md')
if (existsSync(notesPath)) lines.push(readFileSync(notesPath, 'utf8').trim(), '')
mkdirSync(join(root, 'docs', 'i18n'), { recursive: true })
writeFileSync(join(root, 'docs', 'i18n', 'german-sample.md'), lines.join('\n'))
console.log('\nwrote docs/i18n/german-sample.md')
